def _fetch_bound_run(cores: str, execs: list, app_h: float) -> SparkRun:
    stage = StageMetrics(stage_id=9, num_tasks=100, run_time_ms=400_000, fetch_wait_ms=360_000)
    return SparkRun(spark_props={"spark.executor.cores": cores}, stages=[stage],
                    executors=execs, app_end_ts=int(1_000_000_000_000 + app_h * 3_600_000))


def test_fetch_wait_on_a_tiny_denominator_is_not_high() -> None:
    """90% of task time is medium when it is a rounding error against the run's executor-hours."""
    t0 = 1_000_000_000_000
    execs = [ExecutorInfo(exec_id=str(i), added_ts=t0, run_time_ms=3_600_000) for i in range(80)]
    findings = {f.key: f for f in analyze_run(_fetch_bound_run("4", execs, 3))}
    assert findings["shuffle_fetch_wait"].impact == "medium"
    assert findings["shuffle_fetch_wait"].cost_h < 0.1
    assert findings["idle_reserved_executors"].impact == "high"
    assert findings["idle_reserved_executors"].cost_h > 200


def test_fetch_wait_that_is_a_real_share_stays_high() -> None:
    """The gate demotes a small absolute cost, not a large ratio."""
    t0 = 1_000_000_000_000
    execs = [ExecutorInfo(exec_id=str(i), added_ts=t0, removed_ts=t0 + 225_000)
             for i in range(8)]  # 0.5 executor-hours held
    findings = {f.key: f for f in analyze_run(_fetch_bound_run("1", execs, 1))}
    assert findings["shuffle_fetch_wait"].impact == "high"
    assert findings["shuffle_fetch_wait"].cost_h == pytest.approx(0.1)


def test_an_executor_with_no_added_event_still_costs_its_task_span() -> None:
    """One prod log logged ExecutorAdded for 359 of the 497 executors that ran tasks."""
    from airflow_optimizer.crawl import executor_hours
    from airflow_optimizer.eventlog import _task_end

    run = SparkRun(app_end_ts=1_000_000_000_000 + 3_600_000)
    seen: dict = {}

    def execu(eid: str) -> ExecutorInfo:
        return seen.setdefault(eid, ExecutorInfo(exec_id=eid))

    def stage(sid: int, attempt: int = 0) -> StageMetrics:
        return StageMetrics(stage_id=sid)

    _task_end({"Stage ID": 1, "Task End Reason": {"Reason": "Success"},
               "Task Info": {"Executor ID": "7", "Launch Time": 1_000_000_000_000},
               "Task Metrics": {"Executor Run Time": 1000}}, stage, execu)
    run.executors = list(seen.values())
    assert run.executors[0].added_ts == 1_000_000_000_000
    assert executor_hours(run) == pytest.approx(1.0)


def test_slots_come_from_the_log_when_the_property_is_absent() -> None:
    """Both committed fixtures set no spark.executor.cores; a cores=1 fallback inflates the cost."""
    t0 = 1_000_000_000_000
    execs = [ExecutorInfo(exec_id=str(i), cores=4, added_ts=t0, removed_ts=t0 + 2 * 3_600_000)
             for i in range(40)]  # 80 executor-hours held
    stage = StageMetrics(stage_id=1, num_tasks=8000, run_time_ms=8000 * 60_000,
                         fetch_wait_ms=8000 * 45_000)
    run = SparkRun(spark_props={}, stages=[stage], executors=execs,
                   app_end_ts=t0 + 2 * 3_600_000)
    wait = next(f for f in analyze_run(run) if f.key == "shuffle_fetch_wait")
    assert wait.cost_h == pytest.approx(25.0)


def test_a_large_stall_stays_high_on_a_job_too_big_for_its_share_to_show() -> None:
    """300 idle executor-hours is worth an owner's time at any share of the run."""
    t0 = 1_000_000_000_000
    execs = [ExecutorInfo(exec_id=str(i), cores=4, added_ts=t0, removed_ts=t0 + 5 * 3_600_000)
             for i in range(750)]  # 3,750 executor-hours held
    stage = StageMetrics(stage_id=9, num_tasks=9000, run_time_ms=9000 * 400_000,
                         fetch_wait_ms=300 * 3_600_000 * 4)
    run = SparkRun(spark_props={"spark.executor.cores": "4"}, stages=[stage], executors=execs,
                   app_end_ts=t0 + 5 * 3_600_000)
    wait = next(f for f in analyze_run(run) if f.key == "shuffle_fetch_wait")
    assert (wait.impact, round(wait.cost_h)) == ("high", 300)


