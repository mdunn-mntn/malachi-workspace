def test_parse_v2_rolling_dir_reads_all_parts(tmp_path: os.PathLike[str]) -> None:
    """A v2 rolling dir is parsed across ALL events_* parts, in numeric part order.

    Reading only part 1, or reading parts lexically, silently truncates the run.
    """
    import json
    from pathlib import Path

    tmp_path = Path(tmp_path)

    d = tmp_path / "eventlog_v2_batch-test"
    d.mkdir()
    (d / "appstatus_batch-test").write_text("")
    part_events = {
        "events_1_batch-test": [
            {"Event": "SparkListenerApplicationStart", "App Name": "rolling-test",
             "Timestamp": 1000},
            {"Event": "SparkListenerJobStart"},
        ],
        "events_2_batch-test": [{"Event": "SparkListenerJobStart"}],
        "events_10_batch-test": [
            {"Event": "SparkListenerJobStart"},
            {"Event": "SparkListenerApplicationEnd", "Timestamp": 61000},
        ],
    }
    for name, events in part_events.items():
        (d / name).write_text("\n".join(json.dumps(e) for e in events))

    from airflow_optimizer.eventlog import _part_order

    ordered = sorted(part_events, key=_part_order)
    assert ordered == ["events_1_batch-test", "events_2_batch-test", "events_10_batch-test"]

    run = parse_eventlog(str(d))
    assert run.app_name == "rolling-test"
    assert run.jobs == 3  # one per part - fails if only cand[0] is read
    assert run.duration_ms == 60000  # ApplicationEnd lives in the last part


def test_multiframe_zstd_reads_all_frames(tmp_path: os.PathLike[str]) -> None:
    """Concatenated zstd frames (real Spark logs) parse fully - not just frame 1."""
    import json
    import subprocess
    from pathlib import Path

    tmp_path = Path(tmp_path)
    f1 = json.dumps({"Event": "SparkListenerApplicationStart", "App Name": "mf",
                     "App ID": "app-1", "Timestamp": 1000}) + "\n"
    f2 = json.dumps({"Event": "SparkListenerJobStart"}) + "\n" + json.dumps(
        {"Event": "SparkListenerApplicationEnd", "Timestamp": 3000}) + "\n"
    frames = b""
    for chunk in (f1, f2):
        frames += subprocess.run(["zstd", "-q", "-c"], input=chunk.encode(),
                                 capture_output=True).stdout
    log = tmp_path / "multiframe.zstd"
    log.write_bytes(frames)
    run = parse_eventlog(str(log))
    assert run.app_id == "app-1"  # 'App ID' is the real field name, not 'appId'
    assert run.jobs == 1 and run.duration_ms == 2000  # frame 2 content was read


def test_corrupt_zstd_raises_not_clean(tmp_path: os.PathLike[str]) -> None:
    """An undecodable .zstd surfaces as an error - never an empty 'clean' run."""
    from pathlib import Path

